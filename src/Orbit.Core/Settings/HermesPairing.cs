    public static string BuildLocalEnvFile(
        string apiServerKey,
        string orbitCoreUrl,
        string? orbitApiKey,
        string dashboardUsername,
        string dashboardPassword,
        string dashboardSecret)
    {
        var key = string.IsNullOrWhiteSpace(orbitApiKey) ? string.Empty : orbitApiKey.Trim();
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by Orbit — do not commit.");
        sb.AppendLine($"API_SERVER_KEY={apiServerKey.Trim()}");
        sb.AppendLine($"ORBIT_CORE_URL={orbitCoreUrl.Trim().TrimEnd('/')}");
        sb.AppendLine($"ORBIT_API_KEY={key}");
        sb.AppendLine($"HERMES_DASHBOARD_BASIC_AUTH_USERNAME={dashboardUsername.Trim()}");
        sb.AppendLine($"HERMES_DASHBOARD_BASIC_AUTH_PASSWORD={dashboardPassword.Trim()}");
        sb.AppendLine($"HERMES_DASHBOARD_BASIC_AUTH_SECRET={dashboardSecret.Trim()}");
        return sb.ToString();
    }

    private static bool IsLoopbackHostName(string host)
    {
        if (string.Equals(host, "localhost", StringComparison.OrdinalIgnoreCase) ||
            string.Equals(host, "127.0.0.1", StringComparison.OrdinalIgnoreCase) ||
            string.Equals(host, "::1", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        return IPAddress.TryParse(host, out var address) && IPAddress.IsLoopback(address);
    }
}
